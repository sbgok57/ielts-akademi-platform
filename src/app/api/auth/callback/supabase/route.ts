import { NextResponse } from 'next/server';
import { createServerClient } from '@supabase/ssr';
import { cookies } from 'next/headers';

export async function GET(request: Request) {
  const { searchParams, origin } = new URL(request.url);
  const code = searchParams.get('code');
  const next = searchParams.get('next') ?? '/panel';

  if (!code) {
    return NextResponse.redirect(`${origin}/giris?error=missing_code`);
  }

  const cookieStore = await cookies();
  const supabase = createServerClient(
    process.env.NEXT_PUBLIC_SUPABASE_URL!,
    process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY!,
    {
      cookies: {
        getAll: () => cookieStore.getAll(),
        setAll: (cookiesToSet) => {
          cookiesToSet.forEach(({ name, value, options }) =>
            cookieStore.set(name, value, options)
          );
        },
      },
    }
  );

  const { error } = await supabase.auth.exchangeCodeForSession(code);

  if (error) {
    console.error('[auth/callback/supabase] Exchange error:', error.message);
    return NextResponse.redirect(`${origin}/giris?error=auth_callback_failed`);
  }

  // SAFETY: Validate next to prevent open redirect
  const safeNext = next.startsWith('/') && !next.startsWith('//') ? next : '/panel';
  return NextResponse.redirect(`${origin}${safeNext}`);
}
